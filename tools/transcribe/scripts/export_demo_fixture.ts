// Writes tests/fixtures/demo-lessons.json from packages/core's public-domain demos, prepared the
// way the server serves them (prepareLesson: sorted notes, snapped fragments). Re-run after a
// change to packages/core/src/demo.ts; tests/test_fixture.py fails while the two differ.
//   npx tsx tools/transcribe/scripts/export_demo_fixture.ts > tools/transcribe/tests/fixtures/demo-lessons.json
import { demoLessons, prepareLesson, validateLessonInput } from '../../../packages/core/src/index.ts';

const lessons = demoLessons().map((input) => {
  const v = validateLessonInput(input);
  if (!v.ok) throw new Error(v.errors.join('; '));
  const { slug, title, tempo, fragments, notes } = prepareLesson(v.value);
  return { slug, title, tempo, fragments, notes };
});
const _comment =
  'Public-domain demo lessons (packages/core/src/demo.ts) as served by GET /api/lessons/{slug}; ' +
  'test fixtures for hand split + evaluation. Generated by scripts/export_demo_fixture.ts.';
process.stdout.write(JSON.stringify({ _comment, lessons }, null, 1) + '\n');
